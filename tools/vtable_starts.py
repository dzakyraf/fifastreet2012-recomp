#!/usr/bin/env python3
"""Entry points of functions that are reached only through a vtable or a function-pointer table.

Such a function has no .pdata entry and is no `bl` target, so nothing in the recompiler knows it:
it is swallowed into the function before it, and a call through the table finds no code ("indirect
call ... not identified as a function start"; FIFA Street's sub_8338F5B8, called 23,000 times, was
what stopped the front end from ever building a menu).

A code pointer stored in the data is taken as a function start when
  - it is 4-aligned, inside .text, and not a jump-table label (those are code pointers too);
  - the instruction before it ends a function: `blr`, or an unconditional `b` (the tail jump to
    __restgprlr_N the compiler ends most functions with); and
  - a neighbouring word is a code pointer as well (it is one of a run: a vtable), so a stray
    pointer cannot split a function.

usage: vtable_starts.py [--write config/<m>_function_starts.txt]    (module from FIFA_MODULE)
As a module: find(img, base, text, labels) -> set of addresses."""
import re, struct, sys
import title


def labels_of(tables_path):
    out = set()
    try:
        text = open(tables_path).read()
    except FileNotFoundError:
        return out
    for block in text.split("[[switch]]")[1:]:
        out.update(int(x, 16) for x in re.findall(r"0x([0-9A-F]+)", block))
    return out


def find(img, base, text, labels):
    tva, tsz = text
    def w(a): return struct.unpack_from(">I", img, a - base)[0]
    found = set()
    for a in range(base, base + len(img) - 4, 4):
        if tva <= a < tva + tsz:
            continue                                    # data only, not the code itself
        v = w(a)
        if not (tva <= v < tva + tsz) or v & 3 or v in labels:
            continue
        p = w(v - 4)
        ends = p == 0x4E800020 or ((p >> 26) == 18 and not (p & 3))
        if not ends:
            continue
        if sum(1 for n in (w(a - 4), w(a + 4)) if tva <= n < tva + tsz and not n & 3) >= 1:
            found.add(v)
    return found


if __name__ == "__main__":
    img = title.image()
    found = find(img, title.BASE, title.text(img), labels_of(title.TABLES))
    print(f"{title.NAME}: {len(found)} vtable-reachable function starts", file=sys.stderr)
    if "--write" in sys.argv:
        path = sys.argv[sys.argv.index("--write") + 1]
        body = "# Generated by tools/vtable_starts.py -- code reached only through vtables.\n" + \
               "".join(f"{a:08X}\n" for a in sorted(found))
        try:
            same = open(path).read() == body
        except FileNotFoundError:
            same = False
        if not same:
            open(path, "w").write(body)
        sys.exit(0 if same else 1)
